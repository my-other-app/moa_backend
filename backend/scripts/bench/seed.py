"""Fill a scratch database with a MyOtherApp of any size. The defaults are the
year-three world RESULTS.md measured (1,500 clubs, 37,000 events, 60,000
users, 400,000 registrations, 150,000 follows, 20,000 posts); every count is
a flag, and --scale multiplies the ones not given.

    createdb moa_bench
    BENCH_DB=moa_bench python -m scripts.bench.seed                       # schema by alembic, then data
    BENCH_DB=moa_bench python -m scripts.bench.seed --scale 10            # 15k clubs, 370k events, 4M registrations ...
    BENCH_DB=moa_scale python -m scripts.bench.seed --clubs 100000 --upcoming 300000 --past 1000000 \\
        --users 2000000 --registrations 12000000 --follows 4000000 --threads 200000 --sizes-out sizes.json

How it is fast enough for tens of millions of rows:

- Rows go in with COPY (clubs, events, posts: made in Python, where the
  names, cities and dates are) or are generated by Postgres itself from a
  small plan (users, registrations, follows, likes: INSERT … SELECT over
  generate_series), never one statement per row.
- While loading, the session runs with session_replication_role = replica:
  no triggers and no foreign-key checks. Everything is consistent by
  construction, and the trigger-kept counters (events.going_count,
  clubs.follower_count) and the posts' like and comment counts are written
  with the rows, worked out from the same plan the rows come from, so they
  equal what the triggers would have counted (`counters.drift` finds none).
- Secondary indexes are dropped first and built again at the end, in bulk;
  the time each takes to build is reported (a migration at that size takes
  as long).

The spread is meant to look like the real thing: clubs in 68 Indian cities
weighted by size, most with a point of their own; events per club, and
registrations per event, long-tailed (a few events with tens of thousands,
the median a handful), most upcoming events in the coming six weeks, some
online, some paid; follows long-tailed (the most followed club has a large
share of the users). Every draw comes from a seeded generator (Python's and
numpy's, and setseed() for what Postgres draws), so two runs build the same
world relative to the moment they run.
"""
