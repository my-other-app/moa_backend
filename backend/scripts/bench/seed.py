def _txt(v) -> str:
    """One value in COPY's text format."""
    if v is None:
        return r"\N"
    if v is True:
        return "t"
    if v is False:
        return "f"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, datetime):
        return v.isoformat()
    if isinstance(v, Enum):
        return v.name
    if isinstance(v, (list, tuple)):
        return "{" + ",".join(json.dumps(str(x)) for x in v) + "}"
    s = json.dumps(v) if isinstance(v, dict) else str(v)
    if "\\" in s or "\t" in s or "\n" in s or "\r" in s:
        s = s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")
    return s


def _default_text(column, now: datetime) -> str:
    """What the model would have put in a NOT NULL column the row leaves out."""
    d = column.default
    if d is None:
        raise ValueError(f"{column.table.name}.{column.name} is required and has no default")
    arg = d.arg
    if callable(arg):
        try:
            arg = arg(None)
        except TypeError:
            arg = arg()
    if isinstance(arg, datetime):
        arg = now
    if isinstance(arg, (dict, list)) and str(column.type).upper().startswith("JSON"):
        return _txt(json.dumps(arg))
    return _txt(arg)


class Copy:
    """COPY rows into one table in chunks; NOT NULL columns without a database
    default that the rows leave out get the model's default, once."""

    def __init__(self, raw, table: str, columns: list[str], now: datetime, chunk: int = 50000):
        self.raw, self.table, self.chunk = raw, table, chunk
        cur = raw.cursor()
        cur.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name = %s AND is_nullable = 'NO' AND column_default IS NULL",
            (table,),
        )
        required = [r[0] for r in cur.fetchall() if r[0] not in columns]
        model = _Base.metadata.tables[table]
        self.columns = columns + required
        self.suffix = "".join("\t" + _default_text(model.c[c], now) for c in required)
        self.buf = io.StringIO()
        self.n = self.pending = 0

    def add(self, values) -> None:
        self.buf.write("\t".join(map(_txt, values)) + self.suffix + "\n")
        self.n += 1
        self.pending += 1
        if self.pending >= self.chunk:
            self.flush()

    def flush(self) -> None:
        if not self.pending:
            return
        self.buf.seek(0)
        self.raw.cursor().copy_expert(f"COPY {self.table} ({', '.join(self.columns)}) FROM STDIN", self.buf)
        self.buf = io.StringIO()
        self.pending = 0


def _copy_plan(cur, table: str, columns: dict[str, np.ndarray], order=None) -> None:
    """A plan (numpy columns) into a temp table, through COPY."""
    names = list(columns)
    idx = order if order is not None else np.arange(len(columns[names[0]]))
    buf = io.StringIO()
    cols = [columns[k][idx] for k in names]
    for row in zip(*cols):
        buf.write("\t".join(str(v) for v in row) + "\n")
    buf.seek(0)
    cur.copy_expert(f"COPY {table} ({', '.join(names)}) FROM STDIN", buf)


