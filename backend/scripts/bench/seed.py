def schema(db_url: str) -> None:
    from alembic.config import Config
    from alembic import command

    cfg = Config("alembic.ini")
    cfg.set_main_option("sqlalchemy.url", db_url)
    command.upgrade(cfg, "head")


SIZE_TABLES = ("events", "event_registrations_link", "club_users_link", "users", "user_profiles", "user_interests", "clubs",
               "event_interests_link", "club_threads", "thread_likes", "thread_comments", "club_team_members", "event_speakers")


def sizes(engine) -> dict:
    """Rows, heap and index bytes per big table; the database's size; the biggest indexes."""
    with engine.connect() as conn:
        out = dict(database_bytes=conn.execute(text("SELECT pg_database_size(current_database())")).scalar(), tables={}, indexes=[])
        for t in SIZE_TABLES:
            rows = conn.execute(text(f"SELECT count(*) FROM {t}")).scalar()
            heap, idx, total = conn.execute(text(
                f"SELECT pg_relation_size('{t}'), pg_indexes_size('{t}'), pg_total_relation_size('{t}')")).one()
            out["tables"][t] = dict(rows=rows, heap_bytes=heap, index_bytes=idx, total_bytes=total,
                                    bytes_per_row=round(total / rows, 1) if rows else None)
        for name, table, size in conn.execute(text(
            "SELECT indexrelname, relname, pg_relation_size(indexrelid) FROM pg_stat_user_indexes ORDER BY 3 DESC LIMIT 25"
        )).all():
            out["indexes"].append(dict(index=name, table=table, bytes=size))
    return out


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--no-schema", action="store_true", help="the schema is already there")
    p.add_argument("--scale", type=float, default=1.0, help="multiply every count not given explicitly")
    for k, v in DEFAULTS.items():
        p.add_argument(f"--{k}", type=int, default=None, help=f"default {v:,} (times --scale)")
    p.add_argument("--max-event-regs", type=int, default=None,
                   help="the biggest event's registrations (default: 6,000, or 0.2%% of all registrations if that is more)")
    p.add_argument("--sizes-out", help="write row counts, table and index sizes, and the timings here (JSON)")
    args = p.parse_args()
    n = {k: (getattr(args, k) if getattr(args, k) is not None else int(round(v * args.scale))) for k, v in DEFAULTS.items()}
    max_regs = args.max_event_regs or max(6000, int(0.002 * n["registrations"]))
    if not args.no_schema:
        schema(settings.DATABASE_URL_SYNC)
    engine = create_engine(settings.DATABASE_URL_SYNC)
    now = datetime.now(timezone.utc)
    print("seeding", json.dumps(n), f"max_event_regs={max_regs}", flush=True)
    seeder = Seeder(engine, now, n, max_regs)
    stamps = seeder.run()
    got = sizes(engine)
    print("seeded at", now.isoformat())
    print(f"  database {got['database_bytes'] / 2**30:.2f} GiB")
    for t, s in got["tables"].items():
        print(f"  {t:<26} {s['rows']:>11,} rows  heap {s['heap_bytes'] / 2**20:9.1f} MiB  indexes {s['index_bytes'] / 2**20:9.1f} MiB")
    if args.sizes_out:
        with open(args.sizes_out, "w") as f:
            json.dump(dict(counts=n, max_event_regs=max_regs, seeded_at=now.isoformat(), seconds=stamps,
                           index_build_seconds=seeder.index_builds, **got), f, indent=1)


if __name__ == "__main__":
    main()
