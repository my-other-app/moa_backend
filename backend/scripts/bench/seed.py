def zipf(n: int, s: float) -> np.ndarray:
    return 1.0 / np.arange(1, n + 1, dtype=np.float64) ** s


def capped_counts(total: int, weights: np.ndarray, cap: int, rng: np.random.Generator) -> np.ndarray:
    """`total` spread over len(weights) bins in proportion to the weights, no
    bin above `cap`: what a capped bin cannot take goes to the others in
    proportion, and the rounding remainder to bins drawn by weight."""
    w = weights.astype(np.float64).copy()
    counts = np.zeros(len(w), dtype=np.int64)
    capped = np.zeros(len(w), dtype=bool)
    for _ in range(50):
        left = total - int(counts[capped].sum())
        share = np.zeros(len(w))
        share[~capped] = left * w[~capped] / w[~capped].sum()
        over = (~capped) & (share >= cap)
        if not over.any():
            counts[~capped] = np.floor(share[~capped]).astype(np.int64)
            break
        counts[over] = cap
        capped |= over
    rest = total - int(counts.sum())
    open_ = np.flatnonzero(counts < cap)
    while rest > 0 and len(open_):
        p = w[open_] / w[open_].sum()
        add = np.bincount(rng.choice(len(open_), size=rest, p=p), minlength=len(open_))
        add = np.minimum(add, cap - counts[open_])
        counts[open_] += add
        rest -= int(add.sum())
        open_ = np.flatnonzero(counts < cap)
    return counts


def coprime_steps(u: int, rng: np.random.Generator, size: int) -> np.ndarray:
    ok = [p for p in PRIMES if math.gcd(p, u) == 1]
    return np.array(ok, dtype=np.int64)[rng.integers(0, len(ok), size=size)]


def jitter(rng: random.Random, lat: float, lng: float, km: float) -> tuple[float, float]:
    """A point within about `km` of (lat, lng), uniform over the disc."""
    r = km * math.sqrt(rng.random())
    t = rng.random() * 2 * math.pi
    dlat = (r * math.cos(t)) / 111.2
    dlng = (r * math.sin(t)) / (111.2 * math.cos(math.radians(lat)))
    return round(lat + dlat, 6), round(lng + dlng, 6)


